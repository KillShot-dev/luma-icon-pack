def main():
    import argparse
    ap = argparse.ArgumentParser(description="Generate the Luma Android project.")
    ap.add_argument("--flavors", nargs="+", choices=FLAVORS, default=list(FLAVORS),
                    help="Generate ONLY these flavors (default: all). Shared main "
                         "code is always written in full; Phase 6 shared wallpapers, "
                         "app icon and widgets are skipped on a filtered run because "
                         "they already exist in main from Phase 6.")
    args = ap.parse_args()
    global ACTIVE_FLAVORS
    ACTIVE_FLAVORS = list(args.flavors)
    mapping = build_mapping()
    assert len(mapping) == 315, len(mapping)
    n_entries = 0
    for flavor in ACTIVE_FLAVORS:
        n_entries = write_appfilter(flavor, mapping)
        write_drawable_xml(flavor, mapping)
        write_mask_assets(flavor)
    copied = copy_drawables(mapping)
    n_calendar = copy_calendar_days()
    n_wallpapers_p7 = copy_wallpapers_phase7()
    if set(ACTIVE_FLAVORS) == set(FLAVORS):
        n_wallpapers = copy_wallpapers()
        write_app_icon()
        widget_files = write_widgets()
    else:
        n_wallpapers = 0  # shared Phase 6 set already in main; not rewritten
        widget_files = []  # shared providers already in main; not rewritten
    write_dashboard(mapping)
    write_gradle()
    csv_path = write_mapping_csv(mapping)
    comp_pkgs = sorted({p for m in mapping for p in m["packages"] if p in COMPONENTS})
    comp_draw = sorted({m["drawable"] for m in mapping if m["status"] == "component-verified"})
    pkg_only_draw = sorted({m["drawable"] for m in mapping if m["status"] != "component-verified"})
    print(f"icons: {len(mapping)}")
    print(f"appfilter entries (per flavor, identical): {n_entries}")
    print(f"component-verified packages: {len(comp_pkgs)}")
    print(f"component-verified drawables: {len(comp_draw)}")
    rep_draw = sorted({m["drawable"] for m in mapping if m["status"] == "community-reported"})
    print(f"community-reported drawables: {len(rep_draw)}")
    held_draw = sorted({m["drawable"] for m in mapping if m["status"] == "held-out-device-query"})
    print(f"held-out drawables: {len(held_draw)}")
    nf_draw = sorted({m["drawable"] for m in mapping if m["status"] == "not-found-device-query"})
    print(f"not-found drawables: {len(nf_draw)}")
    print(f"package-only drawables: {len(pkg_only_draw)}")
    print(f"flavors generated: {ACTIVE_FLAVORS}")
    print(f"PNG files copied: {copied} (expected {315 * 5 * len(ACTIVE_FLAVORS)})")
    print(f"Phase 6 calendar day drawables copied: {n_calendar} (expected {31 * 5 * len(ACTIVE_FLAVORS)})")
    print(f"Phase 7 per-flavor wallpapers copied: {n_wallpapers_p7} (expected {10 * len([f for f in ACTIVE_FLAVORS if f in ('clear', 'prism', 'midnight')])})")
    print(f"Phase 6 wallpapers copied: {n_wallpapers} (expected 10 on a full run, 0 on a filtered run)")
    print(f"Phase 6 widget files wired: {len(widget_files)}")
    print(f"mapping table: {csv_path}")


if __name__ == "__main__":
    main()
