def copy_calendar_days():
    """Render + copy the Phase 6 dynamic-calendar day drawables.

    Runs the staging script (the single rendering truth — it reuses each
    flavor's own design/png/<set>/<density>/calendar.png as base, white
    bold numbers on tiled sets EXCEPT Prism (#137C63 deep stop, because
    Prism's pale page body makes a white number nearly invisible),
    #059669 on tile-free Glyph, #7C3AED on tile-free Clear) into a temp
    dir, then copies the 620 PNGs (31 days x 4 flavors x 5 densities)
    into the per-flavor drawable dirs, alongside (never instead of)
    calendar.png. Names are calendar_1..calendar_31, NO zero padding.
    """
    import subprocess, tempfile
    script = STAGING / "tools/generate_calendar_days.py"
    if not script.exists():
        raise SystemExit(f"missing calendar script: {script}")
    total = 0
    with tempfile.TemporaryDirectory(prefix="luma-calendar-days-") as tmp:
        r = subprocess.run([sys.executable, str(script), tmp, "--layout", "design",
                            "--sets"] + list(ACTIVE_FLAVORS),
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit(f"calendar script failed: {r.stdout} {r.stderr}")
        for flavor in ACTIVE_FLAVORS:
            for dens, qual in DENS.items():
                dest = APP / "src" / flavor / "res" / f"drawable-{qual}"
                dest.mkdir(parents=True, exist_ok=True)
                for day in range(1, 32):
                    src = Path(tmp) / flavor / dens / f"calendar_{day}.png"
                    if not src.exists():
                        raise SystemExit(f"missing day drawable: {src}")
                    shutil.copyfile(src, dest / f"calendar_{day}.png")
                    total += 1
                padded = list(dest.glob("calendar_0*.png"))
                if padded:
                    raise SystemExit(f"zero-padded day drawable(s): {padded}")
    assert total == 31 * 5 * len(ACTIVE_FLAVORS), total
    return total


