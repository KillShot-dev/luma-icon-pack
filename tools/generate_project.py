def _rounded_mask(size, radius):
    from PIL import Image, ImageDraw
    m = Image.new("L", (size, size), 0)
    ImageDraw.Draw(m).rounded_rectangle([0, 0, size - 1, size - 1], radius=radius, fill=255)
    return m


def _gradient(size, top, bottom):
    from PIL import Image
    img = Image.new("RGB", (size, 1))
    for x in range(size):
        t = x / max(1, size - 1)
        img.putpixel((x, 0), tuple(round(top[i] + (bottom[i] - top[i]) * t) for i in range(3)))
    return img.resize((size, size))


def write_mask_assets(flavor):
    """iconback/iconmask/iconupon at all five densities (48/72/96/144/192).

    Tiled flavors: squircle backplate (flavor-neutral gradient), squircle
    mask (white shape on black), gloss upon (white top gradient clipped to
    the squircle). Tile-free flavors (glyph, clear): transparent
    backplate, NO mask file and NO upon file — the appfilter for those
    flavors references no mask/upon, so launchers draw mapped glyphs
    as-is and leave unmapped apps unthemed rather than forcing them
    into a tile (see README § Mask behavior).
    """
    from PIL import Image, ImageDraw
    size = 192
    base = APP / "src" / flavor / "res"
    densities = {"drawable-mdpi": 48, "drawable-hdpi": 72, "drawable-xhdpi": 96,
                 "drawable-xxhdpi": 144, "drawable-xxxhdpi": 192}
    for qual in densities:
        (base / qual).mkdir(parents=True, exist_ok=True)
    if flavor in TILE_FREE_FLAVORS:
        for qual, px_size in densities.items():
            Image.new("RGBA", (px_size, px_size), (0, 0, 0, 0)).save(base / f"{qual}/iconback.png")
        return
    grads = MASK_GRADS[flavor]
    tile = _gradient(size, *grads).convert("RGBA")
    squircle = _rounded_mask(size, 52)
    tile.putalpha(squircle)
    mask = Image.new("RGB", (size, size), (0, 0, 0))
    mask.paste(Image.new("RGB", (size, size), (255, 255, 255)), mask=squircle)
    # gloss: white, strongest at top, transparent by ~45% height, squircle-clipped
    gloss = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    px = gloss.load()
    for y in range(size):
        a = 0 if y > int(size * 0.45) else int(90 * (1 - y / (size * 0.45)))
        for x in range(size):
            px[x, y] = (255, 255, 255, a)
    gloss.putalpha(Image.composite(gloss.getchannel("A"), Image.new("L", (size, size), 0), squircle))
    for qual, px_size in densities.items():
        tile.resize((px_size, px_size)).save(base / f"{qual}/iconback.png")
        mask.resize((px_size, px_size)).save(base / f"{qual}/iconmask.png")
        gloss.resize((px_size, px_size)).save(base / f"{qual}/iconupon.png")


def write_app_icon():
    """Luma's own launcher icon: ORIGINAL art — a deep-slate squircle tile
    with a white four-point spark (light) mark. Not a brand glyph, not the
    metaPhasic mark, not distorted from any logo. Generated with PIL."""
    from PIL import Image, ImageDraw
    import math
    main = APP / "src/main/res"
    # 432px adaptive foreground: tile fills the FULL canvas (full-bleed).
    # A centred inset tile made the on-device icon visibly differ from the
    # full-bleed 512px store icon, which Google Play rejected 2026-10-29 as
    # a store-listing mismatch (Misleading Claims policy). The spark and dot
    # keep their existing canvas-relative sizes, which already match the
    # store icon (diamond height 51% of canvas, dot ~6.5%).
    fg = Image.new("RGBA", (432, 432), (0, 0, 0, 0))
    tile = _gradient(432, (30, 58, 76), (20, 24, 33)).convert("RGBA")
    tile.putalpha(_rounded_mask(432, 117))
    fg.paste(tile, (0, 0), tile)
    dr = ImageDraw.Draw(fg)
    cx, cy, r = 216, 216, 110
    pts = []
    for ang, rad in [(270, r), (0, r * 0.28), (90, r), (180, r * 0.28),
                     (270, r)]:
        a = math.radians(ang)
        pts.append((cx + rad * math.cos(a), cy + rad * math.sin(a)))
    dr.polygon(pts, fill=(255, 255, 255, 255))
    dr.ellipse([cx - 14, cy - 14, cx + 14, cy + 14], fill=(125, 211, 252, 255))
    (main / "drawable").mkdir(parents=True, exist_ok=True)
    fg.save(main / "drawable/ic_launcher_foreground.png")
    for qual, px in (("mipmap-mdpi", 48), ("mipmap-hdpi", 72), ("mipmap-xhdpi", 96),
                     ("mipmap-xxhdpi", 144), ("mipmap-xxxhdpi", 192)):
        d = main / qual
        d.mkdir(parents=True, exist_ok=True)
        tile2 = _gradient(px, (30, 58, 76), (20, 24, 33)).convert("RGBA")
        tile2.putalpha(_rounded_mask(px, max(12, px * 27 // 100)))
        small = fg.resize((px, px))
        small.save(d / "ic_launcher.png")
        small.save(d / "ic_launcher_round.png")
    (main / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    (main / "mipmap-anydpi-v26/ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '</adaptive-icon>\n')
    (main / "mipmap-anydpi-v26/ic_launcher_round.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '</adaptive-icon>\n')


